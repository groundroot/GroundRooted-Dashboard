import assert from 'node:assert/strict';
import { calculateEstimate, defaultEstimate, requiredNotebooks, validEstimateField } from '../products/local-comparison.ts';
const baseline = calculateEstimate(defaultEstimate);
assert.equal(baseline.pageCount, 1000);
assert.equal(baseline.inputTokens, 2_000_000);
assert.equal(baseline.outputTokens, 1_000_000);
assert.equal(baseline.models[0].usd, 12);
assert.equal(baseline.models[0].krw, 16800);
assert.equal(baseline.models[1].usd, 6);
assert.equal(calculateEstimate({...defaultEstimate,passes:'5'}).models[0].usd,60);
assert.equal(calculateEstimate({...defaultEstimate,image:'0'}).models[0].usd,10);
assert.equal(calculateEstimate({...defaultEstimate,output:'0'}).models[0].usd,4);
assert.equal(calculateEstimate({...defaultEstimate,text:'0',image:'0',output:'0'}).models[0].usd,0);
assert.equal(calculateEstimate({...defaultEstimate,files:'1',pages:'1'}).models[0].usd,.012);
for(const files of ['', '-1', '0', '1.5', '1001', 'NaN', 'Infinity']) assert.equal(calculateEstimate({...defaultEstimate,files}),null);
assert.equal(validEstimateField('exchange','0'),false);
assert.equal(validEstimateField('text','10001'),false);
assert.ok(Number.isFinite(calculateEstimate({...defaultEstimate,files:'1000',pages:'1000',passes:'20',text:'10000',image:'10000',output:'10000',exchange:'10000'}).models[0].krw));
assert.equal(requiredNotebooks(50,50),1);
assert.equal(requiredNotebooks(51,50),2);
assert.equal(requiredNotebooks(500,50),10);
assert.equal(requiredNotebooks(500,600),1);
assert.equal(requiredNotebooks(0,50),null);
console.log('ReadyMD comparison: baseline, repeats, token assumptions, zero cost, validation, bounds and notebook capacities passed.');
